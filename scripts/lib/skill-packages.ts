import { Glob } from "bun";
import { isBuiltin } from "node:module";
import { join } from "node:path";

/**
 * Per-skill package.json generation (#473).
 *
 * `npx skills add aibtcdev/skills/<skill>` copies only the skill's folder.
 * Each skill with scripts therefore carries a package.json that `bun install`
 * resolves on its own: the npm packages it imports, plus this repository
 * (installed from GitHub, no npm registry) when it imports shared code as
 * `@aibtc/skills/...`. Inside the checkout, tsconfig.json maps
 * `@aibtc/skills/*` to the repo root, so nothing needs installing there.
 */

/** Import prefix for code shared from this repository (src/lib, other skills). */
export const REPO_PACKAGE = "@aibtc/skills";

/**
 * Where a copied skill installs the repository from: the default branch, the
 * same commit `npx skills add` copies the skill folder from.
 */
export const REPO_PACKAGE_SOURCE = "github:aibtcdev/skills";

// Bun's own scanner: real import/export/require/import() specifiers only, not
// look-alikes inside strings or templates (e.g. scaffolded code).
const transpiler = new Bun.Transpiler({ loader: "ts" });

function importSpecifiers(source: string): string[] {
  // The scanner rejects a shebang line; blank it out to keep line numbers.
  const code = source.startsWith("#!") ? source.replace(/^#![^\n]*/, "") : source;
  return transpiler.scanImports(code).map((imp) => imp.path);
}

export interface SkillImports {
  /** npm package names (scope included), excluding this repository. */
  npm: Set<string>;
  /** Whether any script imports `@aibtc/skills/...`. */
  usesRepo: boolean;
  /** Relative imports that leave the skill folder, as "file: specifier". */
  escapes: string[];
  /** Number of .ts files scanned (tests excluded). */
  scripts: number;
}

function packageName(specifier: string): string {
  const parts = specifier.split("/");
  return specifier.startsWith("@") ? parts.slice(0, 2).join("/") : parts[0];
}

/** Imports used by a skill's scripts. Test files are skipped: they run only in the checkout. */
export async function scanSkillImports(repoRoot: string, skillDir: string): Promise<SkillImports> {
  const result: SkillImports = { npm: new Set(), usesRepo: false, escapes: [], scripts: 0 };
  const glob = new Glob("**/*.ts");
  for await (const rel of glob.scan({ cwd: join(repoRoot, skillDir) })) {
    if (rel.includes("node_modules/") || rel.endsWith(".test.ts") || rel.endsWith(".d.ts")) continue;
    result.scripts++;
    const text = await Bun.file(join(repoRoot, skillDir, rel)).text();
    for (const spec of importSpecifiers(text)) {
      if (spec.startsWith(".")) {
        // Depth of the importing file inside the skill folder decides how many "../" stay inside it.
        const depth = rel.split("/").length - 1;
        const ups = spec.match(/^(\.\.\/)*/)![0].length / 3;
        if (ups > depth) result.escapes.push(`${rel}: ${spec}`);
        continue;
      }
      if (spec.startsWith("node:") || spec === "bun" || spec.startsWith("bun:") || isBuiltin(spec)) continue;
      const name = packageName(spec);
      if (name === REPO_PACKAGE) result.usesRepo = true;
      else result.npm.add(name);
    }
  }
  return result;
}

export interface SkillPackage {
  /** Expected package.json, or null for a skill without scripts. */
  json: Record<string, unknown> | null;
  /** Problems that make a copied folder unrunnable. */
  errors: string[];
}

/** The package.json a skill folder must carry, derived from its imports and the root dependencies. */
export async function expectedSkillPackage(
  repoRoot: string,
  skillDir: string,
  rootDependencies: Record<string, string>
): Promise<SkillPackage> {
  const imports = await scanSkillImports(repoRoot, skillDir);
  if (imports.scripts === 0) return { json: null, errors: [] };

  const errors = imports.escapes.map(
    (e) => `imports outside its folder (${e}) — import shared code as "${REPO_PACKAGE}/..." instead`
  );
  const dependencies: Record<string, string> = {};
  if (imports.usesRepo) dependencies[REPO_PACKAGE] = REPO_PACKAGE_SOURCE;
  for (const name of [...imports.npm].sort()) {
    const range = rootDependencies[name];
    if (range) dependencies[name] = range;
    else errors.push(`imports "${name}", which the root package.json does not declare in "dependencies"`);
  }
  return {
    json: {
      name: `aibtc-skill-${skillDir}`,
      private: true,
      description: `Dependencies for the ${skillDir} skill when its folder is installed on its own (npx skills add). Generated by \`bun run manifest\`; do not edit.`,
      type: "module",
      dependencies: Object.fromEntries(Object.entries(dependencies).sort(([a], [b]) => a.localeCompare(b))),
    },
    errors,
  };
}

/** Serialized form written to `<skill>/package.json`. */
export function formatSkillPackage(json: Record<string, unknown>): string {
  return JSON.stringify(json, null, 2) + "\n";
}
